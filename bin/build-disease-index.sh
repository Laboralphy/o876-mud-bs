#!/bin/bash

script_folder=$(dirname "$(realpath "$0")")
target_folder=$(realpath "${script_folder}/../src/data/diseases")
output_ts="${target_folder}/index.ts"

source "$script_folder/iterate-files.inc.sh"

# kebab-case filename stem → camelCase variable name (e.g. ghoul-fever → ghoulFever)
toCamelCase() {
    echo "$1" | sed 's/-\([a-z]\)/\u\1/g'
}

# kebab-case filename stem → DISEASE_UPPER_SNAKE const key (e.g. ghoul-fever → DISEASE_GHOUL_FEVER)
toDiseaseConst() {
    echo "DISEASE_$(echo "$1" | tr '[:lower:]' '[:upper:]' | tr '-' '_')"
}

cmdDiseaseImport() {
    local this_file="$1"
    local stem="$(basename "$this_file" .json)"
    local var_name="$(toCamelCase "$stem")"
    echo "import $var_name from './$stem.json';"
}

cmdDiseaseEntry() {
    local this_file="$1"
    local bFirst="$2"
    local stem="$(basename "$this_file" .json)"
    local var_name="$(toCamelCase "$stem")"
    local const_key="$(toDiseaseConst "$stem")"
    echo "    [CONSTS.$const_key]: DiseaseDefinitionSchema.parse($var_name),"
}

generateDiseaseIndex() {
    echo "// File generated by build-disease-index.sh"
    echo ""
    echo "import { DiseaseDefinitionSchema } from '../../schemas/Disease';"
    echo "import type { Disease } from '../../schemas/enums/Disease';"
    echo "import type { z } from 'zod';"
    echo "import { CONSTS } from '../../consts';"
    iterateFiles json "$target_folder" cmdDiseaseImport
    echo ""
    echo "export type DiseaseDefinition = z.infer<typeof DiseaseDefinitionSchema>;"
    echo ""
    echo "const DISEASES: Record<Disease, DiseaseDefinition> = {"
    iterateFiles json "$target_folder" cmdDiseaseEntry
    echo "};"
    echo ""
    echo "export default DISEASES;"
}

generateDiseaseIndex > "$output_ts"
